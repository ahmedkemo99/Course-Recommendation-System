def recommend_courses(course_name, top_n=5):

    if course_name not in course_indices:
        print("Course not found in dataset.")
        return

    idx = course_indices[course_name]

    similarity_scores = list(enumerate(cosine_sim[idx]))

    similarity_scores = sorted(
        similarity_scores,
        key=lambda x: x[1],
        reverse=True
    )

    similarity_scores = similarity_scores[1:top_n+1]

    course_indices_list = [i[0] for i in similarity_scores]

    recommendations = df_clean.iloc[course_indices_list][
        ['Course Name', 'University', 'Difficulty Level', 'Course Rating']
    ].copy()

    recommendations['Similarity Score'] = [
        round(i[1], 4) for i in similarity_scores
    ]

    return recommendations

