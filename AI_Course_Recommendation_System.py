def recommend_for_ui(skills_text, interests_text):

    # Handle empty inputs
    if not skills_text.strip() and not interests_text.strip():
        return pd.DataFrame(), None, "Please enter your skills or interests."

    # Convert comma-separated input to lists
    user_skills = [
        x.strip().lower()
        for x in skills_text.split(",")
        if x.strip()
    ]

    user_interests = [
        x.strip().lower()
        for x in interests_text.split(",")
        if x.strip()
    ]

    # Combine user information
    user_profile = " ".join(user_skills + user_interests)

    # Convert user profile to TF-IDF
    user_vector = tfidf.transform([user_profile])

    # Calculate cosine similarity
    similarity_scores = cosine_similarity(
        user_vector,
        tfidf_matrix
    ).flatten()

    # Get Top 5
    top_n = 5
    top_indices = similarity_scores.argsort()[-top_n:][::-1]

    # Build recommendation table
    results = df_clean.iloc[top_indices][
        [
            "Course Name",
            "University",
            "Difficulty Level",
            "Course Rating",
            "Course URL"
        ]
    ].copy()

    results["Similarity Score"] = similarity_scores[top_indices]

    results["Similarity Score"] = results[
        "Similarity Score"
    ].round(4)

    results = results.reset_index(drop=True)

    # -----------------------------------
    # Build Knowledge Graph
    # -----------------------------------

    G = nx.Graph()

    G.add_node("User", type="User")

    # Add skills/interests
    for skill in user_skills + user_interests:

        G.add_node(skill, type="Skill")
        G.add_edge(
            "User",
            skill,
            relation="HAS_SKILL_OR_INTEREST"
        )

        topic = skill_to_topic.get(skill)

        if topic:

            G.add_node(topic, type="Topic")

            G.add_edge(
                skill,
                topic,
                relation="BELONGS_TO"
            )

    # Add recommended courses
    for idx in top_indices:

        course = df_clean.iloc[idx]["Course Name"]
        skills = df_clean.iloc[idx]["Skills_Clean"].lower()

        G.add_node(course, type="Course")

        # Connect matching skills to courses
        for skill in user_skills:

            pattern = r"\b" + re.escape(skill) + r"\b"

            if re.search(pattern, skills):

                G.add_edge(
                    skill,
                    course,
                    relation="MATCHES"
                )

    # -----------------------------------
    # Draw Graph
    # -----------------------------------

    plt.figure(figsize=(15, 10))

    pos = nx.spring_layout(
        G,
        seed=42,
        k=1.5
    )

    nx.draw(
        G,
        pos,
        with_labels=True,
        node_size=2200,
        font_size=9,
        font_weight="bold"
    )

    plt.title(
        "AI Course Recommendation Knowledge Graph",
        fontsize=16
    )

    plt.tight_layout()

    # Save graph
    graph_path = "/tmp/knowledge_graph.png"

    plt.savefig(
        graph_path,
        dpi=150,
        bbox_inches="tight"
    )

    plt.close()

    message = (
        f"Recommended {len(results)} courses "
        f"for your profile."
    )

    return results, graph_path, message


